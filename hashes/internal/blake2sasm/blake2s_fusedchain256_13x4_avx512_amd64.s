// AVX-512 XMM (four lanes) fused ChainHash cascade kernel for BLAKE2s at the
// 13-byte shape, 4 lanes (1 compression per cascade round). The data
// words are staged once per call and the seed-injected words rebuilt
// each round; see blake2sasm_fused.go for the construction and the
// in-package parity tests for the bit-exact pin against the pure-Go
// cascade.

#include "textflag.h"

#define BLAKE2S_G(a, b, c, d, mx, my) \
	VPADDD b, a, a; \
	VPADDD mx, a, a; \
	VPXORD a, d, d; \
	VPRORD $16, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPRORD $12, b, b; \
	VPADDD b, a, a; \
	VPADDD my, a, a; \
	VPXORD a, d, d; \
	VPRORD $8, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPRORD $7, b, b

#define BLAKE2S_ROUND(s0, s1, s2, s3, s4, s5, s6, s7, s8, s9, s10, s11, s12, s13, s14, s15) \
	BLAKE2S_G(X0, X4, X8, X12, s0, s1); \
	BLAKE2S_G(X1, X5, X9, X13, s2, s3); \
	BLAKE2S_G(X2, X6, X10, X14, s4, s5); \
	BLAKE2S_G(X3, X7, X11, X15, s6, s7); \
	BLAKE2S_G(X0, X5, X10, X15, s8, s9); \
	BLAKE2S_G(X1, X6, X11, X12, s10, s11); \
	BLAKE2S_G(X2, X7, X8, X13, s12, s13); \
	BLAKE2S_G(X3, X4, X9, X14, s14, s15)

