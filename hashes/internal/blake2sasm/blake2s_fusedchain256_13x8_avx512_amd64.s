#include "textflag.h"

#define BLAKE2S_G(a, b, c, d, mx, my) \
	VPADDD b, a, a; \
	VPADDD mx, a, a; \
	VPXORD a, d, d; \
	VPRORD $16, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPRORD $12, b, b; \
	VPADDD b, a, a; \
	VPADDD my, a, a; \
	VPXORD a, d, d; \
	VPRORD $8, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPRORD $7, b, b

#define BLAKE2S_ROUND(s0, s1, s2, s3, s4, s5, s6, s7, s8, s9, s10, s11, s12, s13, s14, s15) \
	BLAKE2S_G(Y0, Y4, Y8, Y12, s0, s1); \
	BLAKE2S_G(Y1, Y5, Y9, Y13, s2, s3); \
	BLAKE2S_G(Y2, Y6, Y10, Y14, s4, s5); \
	BLAKE2S_G(Y3, Y7, Y11, Y15, s6, s7); \
	BLAKE2S_G(Y0, Y5, Y10, Y15, s8, s9); \
	BLAKE2S_G(Y1, Y6, Y11, Y12, s10, s11); \
	BLAKE2S_G(Y2, Y7, Y8, Y13, s12, s13); \
	BLAKE2S_G(Y3, Y4, Y9, Y14, s14, s15)

