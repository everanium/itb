	BLAKE2B_G(Y2, Y6, Y10, Y14, s4, s5); \
	BLAKE2B_G(Y3, Y7, Y11, Y15, s6, s7); \
	BLAKE2B_G(Y0, Y5, Y10, Y15, s8, s9); \
	BLAKE2B_G(Y1, Y6, Y11, Y12, s10, s11); \
