	VPRORQ $24, b, b; \
	VPADDQ b, a, a; \
	VPADDQ my, a, a; \
	VPXORQ a, d, d; \
	VPRORQ $16, d, d; \
	VPADDQ d, c, c; \
	VPXORQ c, b, b; \
	VPRORQ $63, b, b

