	VPXOR c, b, b; \
	VPSHUFB ror24<>(SB), b, b; \
	VPADDQ b, a, a; \
	VPADDQ my(SP), a, a; \
	VPXOR a, d, d; \
	VPSHUFB ror16<>(SB), d, d; \
	VPADDQ d, c, c; \
	VPXOR c, b, b; \
	ROR63(b, t)

