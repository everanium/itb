#include "textflag.h"

#define ROLD(x, n, rn, t) \
	VPSLLD n, x, t; \
	VPSRLD rn, x, x; \
	VPOR t, x, x

#define QR(a, b, c, d, t) \
	VPADDD b, a, a; \
	VPXOR a, d, d; \
	VPSHUFB rol16<>(SB), d, d; \
	VPADDD d, c, c; \
	VPXOR c, b, b; \
	ROLD(b, $12, $20, t); \
	VPADDD b, a, a; \
	VPXOR a, d, d; \
	VPSHUFB rol8<>(SB), d, d; \
	VPADDD d, c, c; \
	VPXOR c, b, b; \
	ROLD(b, $7, $25, t)

#define K(j)   (j*32)
#define V15    256
#define V12    288

#define DR \
	QR(Y0, Y4, Y8,  Y12, Y15); \
	QR(Y1, Y5, Y9,  Y13, Y15); \
	QR(Y2, Y6, Y10, Y14, Y15); \
	VMOVDQU Y12, V12(SP); \
	VMOVDQU V15(SP), Y15; \
	QR(Y3, Y7, Y11, Y15, Y12); \
	QR(Y0, Y5, Y10, Y15, Y12); \
	VMOVDQU Y15, V15(SP); \
	VMOVDQU V12(SP), Y12; \
	QR(Y1, Y6, Y11, Y12, Y15); \
	QR(Y2, Y7, Y8,  Y13, Y15); \
	QR(Y3, Y4, Y9,  Y14, Y15)

