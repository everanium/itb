// AVX-512 XMM (four lanes) fused ChainHash cascade kernel for ChaCha20 at the
// 13-byte shape, 4 lanes (1 keystream block per cascade round). The data
// words are staged once per call and the key words rebuilt each round;
// see chacha20asm_fused.go for the construction and the in-package
// parity tests for the bit-exact pin against the pure-Go cascade.

#include "textflag.h"

#define CHACHA_QR(a, b, c, d) \
	VPADDD b, a, a; \
	VPXORD a, d, d; \
	VPROLD $16, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPROLD $12, b, b; \
	VPADDD b, a, a; \
	VPXORD a, d, d; \
	VPROLD $8, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPROLD $7, b, b

#define CHACHA_DR \
	CHACHA_QR(X0, X4, X8, X12); \
	CHACHA_QR(X1, X5, X9, X13); \
	CHACHA_QR(X2, X6, X10, X14); \
	CHACHA_QR(X3, X7, X11, X15); \
	CHACHA_QR(X0, X5, X10, X15); \
	CHACHA_QR(X1, X6, X11, X12); \
	CHACHA_QR(X2, X7, X8, X13); \
	CHACHA_QR(X3, X4, X9, X14)

