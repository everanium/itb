	VPXOR c, b, b; \
	ROLD(b, $12, $20, t); \
	VPADDD b, a, a; \
	VPXOR a, d, d; \
	VPSHUFB rol8<>(SB), d, d; \
	VPADDD d, c, c; \
	VPXOR c, b, b; \
	ROLD(b, $7, $25, t)

