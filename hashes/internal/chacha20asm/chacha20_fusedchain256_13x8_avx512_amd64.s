	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPROLD $12, b, b; \
	VPADDD b, a, a; \
	VPXORD a, d, d; \
	VPROLD $8, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPROLD $7, b, b

