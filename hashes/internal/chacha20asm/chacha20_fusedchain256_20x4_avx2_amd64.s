#define ROLD(x, n, rn, t) \
	VPSLLD n, x, t; \
	VPSRLD rn, x, x; \
	VPOR t, x, x

#define QR(a, b, c, d, t) \
	VPADDD b, a, a; \
	VPXOR a, d, d; \
	VPSHUFB rol16<>(SB), d, d; \
	VPADDD d, c, c; \
	VPXOR c, b, b; \
	ROLD(b, $12, $20, t); \
	VPADDD b, a, a; \
	VPXOR a, d, d; \
	VPSHUFB rol8<>(SB), d, d; \
	VPADDD d, c, c; \
	VPXOR c, b, b; \
	ROLD(b, $7, $25, t)

