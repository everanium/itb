// AVX2 VEX YMM (one lane per qword, synthesised rotates) fused ChainHash cascade kernel for SipHash-2-4-128 at the
// 20-byte shape, 4 lanes (3 message words, 14 SipRounds per cascade
// round). The words are packed once and every cascade round re-keys the
// state from the previous round's output; see siphashasm_fused.go for the
// construction and the in-package parity tests for the bit-exact pin
// against the pure-Go cascade.

