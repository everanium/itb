	VAESENC X11, X0, X0; VAESENC X11, X1, X1; VAESENC X11, X2, X2; VAESENC X11, X3, X3; VAESENC X11, X4, X4; VAESENC X11, X5, X5; VAESENC X11, X6, X6; VAESENC X11, X7, X7
