// VEX-encoded AES-NI XMM (VAESENC xmm, xmm, xmm; needs AES-NI + AVX) 16-lane fused ChainHash cascade kernel for AES-CMAC
// at the 13-byte per-lane fill shape (1 zero-padded block, 1 AES-128
// permutation per lane and cascade round). See aescmacasm_fused.go for
// the construction; every tier is pinned to the pure-Go reference
// (scalarFusedX16) by the in-package parity tests.
//
// Unique to the batch-16 kernel: groupIdx is synthesized in-register from
// groupIdxBase per lane, avoiding the per-lane pointer gather overhead of
// the x4 path. The synthesised block is round-invariant per lane and
// carries K0 and the length tag; every cascade round XORs the pair and
// the block into the state and runs the ten AES rounds under K1..K10.
//
// Batch layout: two batches of 8 lanes; each batch runs the whole cascade
// before the next starts. The 16 blocks are staged once into the frame
// (16 bytes per lane) in the prologue. Per batch: X0–X7 states,
// X8–X15 K1..K8 (K9 / K10 as memory operands).

#include "textflag.h"

// func aesCMAC128FusedChain13x16VexAsm(roundKeys *[176]byte, comps *uint64, nPairs int, groupIdxBase uint64, out *[16][2]uint64)
TEXT ·aesCMAC128FusedChain13x16VexAsm(SB), NOSPLIT, $256-40
	MOVQ roundKeys+0(FP), AX
	MOVQ out+32(FP), DI
	MOVQ groupIdxBase+24(FP), R8

	// Template X12 = absorb13Block ^ K0 ^ (13 || 13)
	VMOVDQU ·absorb13Block(SB), X12
	MOVQ $13, R12
	VPXOR 0(AX), X12, X12
	VMOVQ R12, X10
	VPUNPCKLQDQ X10, X10, X10
	VPXOR X10, X12, X12

	// Stage the 16 fill blocks into the frame at 16*lane(SP)
	// Lane 0: idx = base
	MOVQ R8, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 0(SP)

	// Lane 1: idx = base + 1
	MOVQ R8, R9
	ADDQ $1, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 16(SP)

	// Lane 2: idx = base + 2
	MOVQ R8, R9
	ADDQ $2, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 32(SP)

	// Lane 3: idx = base + 3
	MOVQ R8, R9
	ADDQ $3, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 48(SP)

	// Lane 4: idx = base + 4
	MOVQ R8, R9
