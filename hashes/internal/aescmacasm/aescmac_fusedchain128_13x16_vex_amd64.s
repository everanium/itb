// VEX-encoded AES-NI XMM (VAESENC xmm, xmm, xmm; needs AES-NI + AVX) 16-lane fused ChainHash cascade kernel for AES-CMAC
// at the 13-byte per-lane fill shape (1 zero-padded block, 1 AES-128
// permutation per lane and cascade round). See aescmacasm_fused.go for
// the construction; every tier is pinned to the pure-Go reference
// (scalarFusedX16) by the in-package parity tests.
//
// Unique to the batch-16 kernel: groupIdx is synthesized in-register from
// groupIdxBase per lane, avoiding the per-lane pointer gather overhead of
// the x4 path. The synthesised block is round-invariant per lane and
// carries the interlock-nonce fold v at bytes 9..12 and the length tag.
// Every lane is carried as t = state ^ K0: t
// starts at K0, every cascade round XORs the pair and the block into t
// and runs nine AES rounds under K1..K9 and the last under
// K10' = K10 ^ K0 (AESENCLAST(s, K10) ^ K0 = AESENCLAST(s, K10 ^ K0)),
// and the lane output is t ^ K0. K0 and K10' exist only in registers;
// the frame holds the public blocks only.
//
// Batch layout: two batches of 8 lanes; each batch runs the whole cascade
// before the next starts. The 16 blocks are staged once into the frame
// (16 bytes per lane) in the prologue from the template in X12 —
// absorb13Block XOR [13 | 13 ^ (v << 8)], the length tag with the
// interlock-nonce fold in its second qword. Per batch: X0–X7 states,
// X8–X14 K1..K7, X15 K10' (K8 / K9 as memory operands read from
// the schedule).

#include "textflag.h"

// func aesCMAC128FusedChain13x16VexAsm(roundKeys *[176]byte, comps *uint64, nPairs int, groupIdxBase uint64, out *[16][2]uint64, v uint32)
TEXT ·aesCMAC128FusedChain13x16VexAsm(SB), NOSPLIT, $256-44
	MOVQ roundKeys+0(FP), AX
	MOVQ out+32(FP), DI
	MOVQ groupIdxBase+24(FP), R8

	// Template X12 = absorb13Block ^ [13 | 13 ^ (v << 8)]: the length tag with the
	// interlock-nonce fold v in bytes 9..12 of the second qword
	VMOVDQU ·absorb13Block(SB), X12
	MOVQ $13, R12
	MOVL v+40(FP), R9
	SHLQ $8, R9
	ORQ R12, R9
	VMOVQ R12, X10
	VPINSRQ $1, R9, X10, X10
	VPXOR X10, X12, X12

	// Stage the 16 fill blocks into the frame at 16*lane(SP)
	// Lane 0: idx = base
	MOVQ R8, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 0(SP)

	// Lane 1: idx = base + 1
	MOVQ R8, R9
	ADDQ $1, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 16(SP)

	// Lane 2: idx = base + 2
	MOVQ R8, R9
	ADDQ $2, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 32(SP)

	// Lane 3: idx = base + 3
	MOVQ R8, R9
	ADDQ $3, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 48(SP)

	// Lane 4: idx = base + 4
	MOVQ R8, R9
	ADDQ $4, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 64(SP)

	// Lane 5: idx = base + 5
	MOVQ R8, R9
	ADDQ $5, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 80(SP)

	// Lane 6: idx = base + 6
	MOVQ R8, R9
	ADDQ $6, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 96(SP)

	// Lane 7: idx = base + 7
	MOVQ R8, R9
	ADDQ $7, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
