	// Load K1..K8 (K9 / K10 are read as memory operands)
	VMOVDQU 16(AX), X8
	VMOVDQU 32(AX), X9
	VMOVDQU 48(AX), X10
	VMOVDQU 64(AX), X11
	VMOVDQU 80(AX), X12
	VMOVDQU 96(AX), X13
