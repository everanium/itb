	ADDQ $6, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
	VPSRLQ $56, X15, X15
	VPUNPCKLQDQ X15, X11, X11
	VPXOR X12, X11, X11
	VMOVDQU X11, 96(SP)

