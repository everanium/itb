	VPXOR X12, X11, X11
	VMOVDQU X11, 240(SP)

	// Load K1..K7 and K10' = K10 ^ K0 (K8 / K9 are read as memory operands)
	VMOVDQU 16(AX), X8
	VMOVDQU 32(AX), X9
	VMOVDQU 48(AX), X10
	VMOVDQU 64(AX), X11
	VMOVDQU 80(AX), X12
	VMOVDQU 96(AX), X13
	VMOVDQU 112(AX), X14
	VMOVDQU 160(AX), X15
	VPXOR 0(AX), X15, X15

	// ========== BATCH 1: lanes 0–7 ==========
	MOVQ comps+8(FP), BX
	MOVQ nPairs+16(FP), CX
	VMOVDQU 0(AX), X0
	VMOVDQU 0(AX), X1
	VMOVDQU 0(AX), X2
	VMOVDQU 0(AX), X3
