	VAESENC Z9, Z0, Z0
	VAESENCLAST Z10, Z0, Z0
	VPXORD Z16, Z0, Z0
	VAESENC Z1, Z0, Z0
	VAESENC Z2, Z0, Z0
	VAESENC Z3, Z0, Z0
	VAESENC Z4, Z0, Z0
	VAESENC Z5, Z0, Z0
	VAESENC Z6, Z0, Z0
