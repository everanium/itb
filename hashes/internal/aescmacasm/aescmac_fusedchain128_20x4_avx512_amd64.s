	VBROADCASTI32X4 0(BX), Z11
	VPTERNLOGQ $0x96, Z11, Z15, Z0
	VAESENC Z1, Z0, Z0
	VAESENC Z2, Z0, Z0
	VAESENC Z3, Z0, Z0
	VAESENC Z4, Z0, Z0
	VAESENC Z5, Z0, Z0
	VAESENC Z6, Z0, Z0
	VAESENC Z7, Z0, Z0
