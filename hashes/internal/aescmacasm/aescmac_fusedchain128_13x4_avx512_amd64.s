	JNZ loop

	VMOVDQU X0, 0(DI)
	VEXTRACTI64X2 $1, Z0, 16(DI)
	VEXTRACTI64X2 $2, Z0, 32(DI)
	VEXTRACTI64X2 $3, Z0, 48(DI)
	VPXORD X0, X0, X0
	VPXORD X1, X1, X1
	VPXORD X2, X2, X2
	VPXORD X3, X3, X3
