	MOVQ out+32(FP), DI
	MOVQ 0(DX), R8
	MOVQ 8(DX), R9
	MOVQ 16(DX), R10
	MOVQ 24(DX), R11

	VPXORD Z12, Z12, Z12
	VBROADCASTI32X4 0(AX), Z13
	MOVQ $13, R12
	VPBROADCASTQ R12, Z14
