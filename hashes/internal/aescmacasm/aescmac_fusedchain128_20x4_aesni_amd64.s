//go:build amd64 && !purego && !noitbasm

// Legacy-SSE AES-NI XMM fused ChainHash cascade kernel for AES-CMAC at the
// 20-byte shape, 4 lanes (2 zero-padded blocks, 2 AES-128
// permutations per cascade round).
// The data blocks are staged once into the frame with K0 (and, for
// block 0, the length tag) folded in, and every cascade round runs
// from those 16-byte slots; see aescmacasm_fused.go for the
// construction and the in-package parity tests for the bit-exact pin
// against the pure-Go cascade.

#include "textflag.h"

// func aesCMAC128FusedChain20x4AesNiAsm(roundKeys *[176]byte, comps *uint64, nPairs int, dataPtrs *[4]*byte, out *[4][2]uint64)
TEXT ·aesCMAC128FusedChain20x4AesNiAsm(SB), NOSPLIT, $128-40
	MOVQ roundKeys+0(FP), AX
	MOVQ comps+8(FP), BX
	MOVQ nPairs+16(FP), CX
	MOVQ dataPtrs+24(FP), DX
	MOVQ out+32(FP), DI
	MOVQ 0(DX), R8
	MOVQ 8(DX), R9
	MOVQ 16(DX), R10
	MOVQ 24(DX), R11

	PXOR X13, X13
	MOVOU 0(AX), X14
	MOVQ $20, R12
	MOVQ R12, X15
	PUNPCKLQDQ X15, X15
	PXOR X14, X15
	MOVOU X13, X4
	PINSRD $0, 0(R8), X4
	PINSRD $1, 4(R8), X4
	PINSRQ $1, 8(R8), X4
	PXOR X15, X4
	MOVOU X4, 0(SP)
	MOVOU X13, X4
	PINSRD $0, 0(R9), X4
	PINSRD $1, 4(R9), X4
	PINSRQ $1, 8(R9), X4
	PXOR X15, X4
	MOVOU X4, 16(SP)
	MOVOU X13, X4
	PINSRD $0, 0(R10), X4
	PINSRD $1, 4(R10), X4
	PINSRQ $1, 8(R10), X4
	PXOR X15, X4
	MOVOU X4, 32(SP)
	MOVOU X13, X4
	PINSRD $0, 0(R11), X4
	PINSRD $1, 4(R11), X4
	PINSRQ $1, 8(R11), X4
	PXOR X15, X4
	MOVOU X4, 48(SP)
	MOVOU X13, X4
	PINSRD $0, 16(R8), X4
	PXOR X14, X4
	MOVOU X4, 64(SP)
	MOVOU X13, X4
	PINSRD $0, 16(R9), X4
	PXOR X14, X4
	MOVOU X4, 80(SP)
	MOVOU X13, X4
	PINSRD $0, 16(R10), X4
	PXOR X14, X4
	MOVOU X4, 96(SP)
	MOVOU X13, X4
	PINSRD $0, 16(R11), X4
	PXOR X14, X4
	MOVOU X4, 112(SP)

	MOVOU 16(AX), X6
	MOVOU 32(AX), X7
	MOVOU 48(AX), X8
	MOVOU 64(AX), X9
	MOVOU 80(AX), X10
	MOVOU 96(AX), X11
	MOVOU 112(AX), X12
	MOVOU 128(AX), X13
	MOVOU 144(AX), X14
	MOVOU 160(AX), X15
	PXOR X0, X0
	PXOR X1, X1
	PXOR X2, X2
	PXOR X3, X3

loop:
	MOVOU 0(BX), X5
	PXOR X5, X0
	PXOR X5, X1
	PXOR X5, X2
	PXOR X5, X3
	MOVOU 0(SP), X4
	PXOR X4, X0
	MOVOU 16(SP), X4
	PXOR X4, X1
	MOVOU 32(SP), X4
	PXOR X4, X2
	MOVOU 48(SP), X4
	PXOR X4, X3
	AESENC X6, X0; AESENC X6, X1; AESENC X6, X2; AESENC X6, X3
	AESENC X7, X0; AESENC X7, X1; AESENC X7, X2; AESENC X7, X3
	AESENC X8, X0; AESENC X8, X1; AESENC X8, X2; AESENC X8, X3
	AESENC X9, X0; AESENC X9, X1; AESENC X9, X2; AESENC X9, X3
	AESENC X10, X0; AESENC X10, X1; AESENC X10, X2; AESENC X10, X3
	AESENC X11, X0; AESENC X11, X1; AESENC X11, X2; AESENC X11, X3
	AESENC X12, X0; AESENC X12, X1; AESENC X12, X2; AESENC X12, X3
	AESENC X13, X0; AESENC X13, X1; AESENC X13, X2; AESENC X13, X3
	AESENC X14, X0; AESENC X14, X1; AESENC X14, X2; AESENC X14, X3
	AESENCLAST X15, X0; AESENCLAST X15, X1; AESENCLAST X15, X2; AESENCLAST X15, X3
	MOVOU 64(SP), X4
	PXOR X4, X0
	MOVOU 80(SP), X4
	PXOR X4, X1
	MOVOU 96(SP), X4
	PXOR X4, X2
	MOVOU 112(SP), X4
	PXOR X4, X3
	AESENC X6, X0; AESENC X6, X1; AESENC X6, X2; AESENC X6, X3
	AESENC X7, X0; AESENC X7, X1; AESENC X7, X2; AESENC X7, X3
	AESENC X8, X0; AESENC X8, X1; AESENC X8, X2; AESENC X8, X3
	AESENC X9, X0; AESENC X9, X1; AESENC X9, X2; AESENC X9, X3
	AESENC X10, X0; AESENC X10, X1; AESENC X10, X2; AESENC X10, X3
	AESENC X11, X0; AESENC X11, X1; AESENC X11, X2; AESENC X11, X3
	AESENC X12, X0; AESENC X12, X1; AESENC X12, X2; AESENC X12, X3
	AESENC X13, X0; AESENC X13, X1; AESENC X13, X2; AESENC X13, X3
	AESENC X14, X0; AESENC X14, X1; AESENC X14, X2; AESENC X14, X3
	AESENCLAST X15, X0; AESENCLAST X15, X1; AESENCLAST X15, X2; AESENCLAST X15, X3
