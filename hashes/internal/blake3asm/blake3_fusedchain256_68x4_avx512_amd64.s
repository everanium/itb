	VPXORD a, d, d; \
	VPRORD $16, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPRORD $12, b, b; \
	VPADDD b, a, a; \
	VPADDD my, a, a; \
	VPXORD a, d, d; \
	VPRORD $8, d, d; \
	VPADDD d, c, c; \
	VPXORD c, b, b; \
	VPRORD $7, b, b

