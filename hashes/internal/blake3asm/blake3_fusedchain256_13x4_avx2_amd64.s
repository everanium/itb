#define RORD(x, n, ln, t) \
	VPSRLD n, x, t; \
	VPSLLD ln, x, x; \
	VPOR t, x, x

#define GA(a, b, c, d, mx, my, t) \
	VPADDD b, a, a; \
	VPADDD mx(SP), a, a; \
	VPXOR a, d, d; \
	VPSHUFB ror16<>(SB), d, d; \
	VPADDD d, c, c; \
	VPXOR c, b, b; \
	RORD(b, $12, $20, t); \
	VPADDD b, a, a; \
	VPADDD my(SP), a, a; \
	VPXOR a, d, d; \
	VPSHUFB ror8<>(SB), d, d; \
	VPADDD d, c, c; \
	VPXOR c, b, b; \
	RORD(b, $7, $25, t)

