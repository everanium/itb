// aesitbWords16 lays a HashFunc128 (lo, hi) pair out as the 16-byte
// little-endian block the reference API returns.
func aesitbWords16(lo, hi uint64) [16]byte {
	var out [16]byte
	for i := 0; i < 8; i++ {
		out[i] = byte(lo >> (8 * i))
		out[8+i] = byte(hi >> (8 * i))
	}
	return out
}

func TestAESITBParityGeneric(t *testing.T) {
	single, _, key, err := hashes.Make128Pair(hashes.CipherAESITB128, aesitbParityKey[:])
	if err != nil {
		t.Fatalf("Make128Pair: %v", err)
	}
	if string(key) != string(aesitbParityKey[:]) {
		t.Fatalf("Make128Pair returned key %x, want %x", key, aesitbParityKey)
	}
	for _, v := range aesitbGenericVectors {
		data := aesitbParityData(v.dataLen)
		lo, hi := single(data, v.seed0, v.seed1)
		p := aesitbWords16(lo, hi)
		r := aesitb.HashGeneric(aesitbParityKey, data, v.seed0, v.seed1)
		if p != r {
			t.Errorf("len=%d seeds=(%#x,%#x): production %x != reference %x", v.dataLen, v.seed0, v.seed1, p, r)
		}
		if got := hex.EncodeToString(p[:]); got != v.want {
			t.Errorf("len=%d seeds=(%#x,%#x): got %s want %s", v.dataLen, v.seed0, v.seed1, got, v.want)
		}
	}
}

func TestAESITBParityBatch(t *testing.T) {
	single, batched, _, err := hashes.Make128Pair(hashes.CipherAESITB128, aesitbParityKey[:])
	if err != nil {
		t.Fatalf("Make128Pair: %v", err)
	}
	if batched == nil {
		t.Fatal("Make128Pair returned a nil batched arm for aesitb128")
	}
	// Four lanes with distinct lengths (empty, tail-only, full block,
	// multi-block) and distinct seeds, all drawn from the generic vectors.
	picks := []int{0, 12, 13, 15}
	var lanes [4][]byte
	var seeds [4][2]uint64
	for i, p := range picks {
		v := aesitbGenericVectors[p]
		lanes[i] = aesitbParityData(v.dataLen)
		seeds[i] = [2]uint64{v.seed0, v.seed1}
	}
	out := batched(&lanes, seeds)
	for i, p := range picks {
		v := aesitbGenericVectors[p]
		lo, hi := single(lanes[i], seeds[i][0], seeds[i][1])
		if out[i][0] != lo || out[i][1] != hi {
			t.Errorf("lane %d: batched (%#x,%#x) != single (%#x,%#x)", i, out[i][0], out[i][1], lo, hi)
		}
		b := aesitbWords16(out[i][0], out[i][1])
		r := aesitb.HashGeneric(aesitbParityKey, lanes[i], seeds[i][0], seeds[i][1])
		if b != r {
			t.Errorf("lane %d: batched %x != reference %x", i, b, r)
		}
		if got := hex.EncodeToString(b[:]); got != v.want {
			t.Errorf("lane %d: got %s want %s", i, got, v.want)
		}
	}
}

// --- Batched arm benchmark ---

// BenchmarkAESITBBatchedArm compares the aesitb128 batched arm (4-lane
// chain-absorb reference) against four calls of the single arm on the
// same inputs, per per-pixel shape. Bytes/op = 4 × shape.
func BenchmarkAESITBBatchedArm(b *testing.B) {
	single, batched, _, err := hashes.Make128Pair(hashes.CipherAESITB128, aesitbParityKey[:])
	if err != nil {
		b.Fatal(err)
	}
	for _, n := range []int{13, 20, 36, 68} {
		var lanes [4][]byte
		for i := range lanes {
			lanes[i] = aesitbParityData(n)
		}
		seeds := [4][2]uint64{{1, 2}, {3, 4}, {5, 6}, {7, 8}}
		b.Run(fmt.Sprintf("single4/shape%d", n), func(b *testing.B) {
			b.SetBytes(int64(4 * n))
			b.ReportAllocs()
			var sink uint64
			for i := 0; i < b.N; i++ {
				for l := 0; l < 4; l++ {
					lo, _ := single(lanes[l], seeds[l][0]^uint64(i), seeds[l][1])
					sink ^= lo
				}
			}
			_ = sink
		})
		b.Run(fmt.Sprintf("batched/shape%d", n), func(b *testing.B) {
			b.SetBytes(int64(4 * n))
			b.ReportAllocs()
			var sink uint64
			for i := 0; i < b.N; i++ {
				seeds[0][0] = uint64(i)
				out := batched(&lanes, seeds)
				sink ^= out[0][0]
			}
			_ = sink
		})
	}
}

// --- Dispatch tiers and round constants ---

// tierFlags is a snapshot of the aesitbasm dispatch flags — the
// fused-cascade family.
type tierFlags struct {
	fzmm, fymm, fvex, faesni, farm bool
}

func readTierFlags() tierFlags {
	return tierFlags{
		aesitbasm.FusedHasVAESAVX512, aesitbasm.FusedHasVAESAVX2,
		aesitbasm.FusedHasAVXAESNI, aesitbasm.FusedHasAESNI, aesitbasm.FusedHasARMAES,
	}
}

func (f tierFlags) apply() {
	aesitbasm.FusedHasVAESAVX512, aesitbasm.FusedHasVAESAVX2 = f.fzmm, f.fymm
	aesitbasm.FusedHasAVXAESNI, aesitbasm.FusedHasAESNI, aesitbasm.FusedHasARMAES = f.fvex, f.faesni, f.farm
}

// withTierFlags installs f for the remainder of the test and registers a
// Cleanup that restores the flags the test started with, so every test
// that mutates the package-level dispatch flags leaves them as found
// regardless of how it exits.
func withTierFlags(t *testing.T, f tierFlags) {
	t.Helper()
	saved := readTierFlags()
	t.Cleanup(saved.apply)
	f.apply()
}

// TestAESITBCrossTierRoundTrip encrypts under one dispatch tier and
// decrypts under the other, both directions, on the AES-ITB Single
// Message and Streaming AEAD profiles. The per-pixel hash is the same
// function on every tier, so wire produced by the scalar reference must
// decrypt under the SIMD tier and vice versa.
func TestAESITBCrossTierRoundTrip(t *testing.T) {
	auto := readTierFlags()
	if auto == (tierFlags{}) {
		t.Skip("no assembly tier on this host; scalar is the only path")
	}
	scalar := tierFlags{}

	plain := make([]byte, 300_000)
	rand.Read(plain)

	for _, tc := range []struct {
		profile   string
		streaming bool
	}{
		{triple.ProfileSingleMsgAESITBNoMACV1, false},
		{triple.ProfileSingleMsgAESITBMACV1, false},
		{triple.ProfileStreamingAEADAESITBMACV1, true},
	} {
		t.Run(tc.profile, func(t *testing.T) {
			withTierFlags(t, auto)
			p, _, err := triple.Init(tc.profile, triple.Opts{})
			if err != nil {
				t.Fatalf("Init: %v", err)
			}
			defer p.Close()
			enc := func(in []byte) ([]byte, error) {
				if tc.streaming {
					return p.EncryptStreamBytes(in)
				}
				return p.EncryptMessage(in)
			}
			dec := func(in []byte) ([]byte, error) {
				if tc.streaming {
					return p.DecryptStreamBytes(in)
				}
				return p.DecryptMessage(in)
			}

			scalar.apply()
			wireScalar, err := enc(plain)
			if err != nil {
				t.Fatalf("scalar encrypt: %v", err)
			}
			auto.apply()
			wireAuto, err := enc(plain)
			if err != nil {
				t.Fatalf("auto-tier encrypt: %v", err)
			}

			got, err := dec(wireScalar)
			if err != nil || !bytes.Equal(got, plain) {
				t.Fatalf("scalar wire under auto tier: err=%v match=%v", err, bytes.Equal(got, plain))
			}
			scalar.apply()
			got, err = dec(wireAuto)
			if err != nil || !bytes.Equal(got, plain) {
				t.Fatalf("auto-tier wire under scalar: err=%v match=%v", err, bytes.Equal(got, plain))
			}
		})
	}
}

