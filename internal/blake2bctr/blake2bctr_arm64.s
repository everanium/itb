	VADD mx.D2, a.D2, a.D2; \
	VEOR a.B16, d.B16, d.B16; \
	VREV64 d.S4, d.S4; \
	VADD d.D2, c.D2, c.D2; \
	VEOR c.B16, b.B16, b.B16; \
	VSHL $40, b.D2, V16.D2; \
	VSRI $24, b.D2, V16.D2; \
	VADD V16.D2, a.D2, a.D2; \
	VADD my.D2, a.D2, a.D2; \
	VEOR a.B16, d.B16, b.B16; \
	VSHL $48, b.D2, d.D2; \
	VSRI $16, b.D2, d.D2; \
	VADD d.D2, c.D2, c.D2; \
	VEOR c.B16, V16.B16, V16.B16; \
	VSHL $1, V16.D2, b.D2; \
	VSRI $63, V16.D2, b.D2

