//go:build amd64 && !purego && !noitbasm

// VEX-encoded AES-NI XMM (eight state chains) fused ChainHash cascade kernel for AES-ITB-128 at the
// 20-byte shape, 8 lanes (2 PKCS#7 blocks, 4 AES rounds per
// cascade round).
// The padded data blocks are staged once into the frame and every
// cascade round runs from those 16-byte slots; see aesitbasm_fused.go for the
// construction and the in-package parity tests for the bit-exact pin
// against the pure-Go cascade.

#include "textflag.h"

// func aesITB128FusedChain20x8VexAsm(key *[16]byte, comps *uint64, nPairs int, dataPtrs *[8]*byte, out *[8][2]uint64)
TEXT ·aesITB128FusedChain20x8VexAsm(SB), NOSPLIT, $256-40
	MOVQ key+0(FP), AX
	MOVQ comps+8(FP), BX
	MOVQ nPairs+16(FP), CX
	MOVQ dataPtrs+24(FP), DX
	MOVQ out+32(FP), DI

	VMOVDQU ·pad4Tail(SB), X13
	// Lanes 0..3
	MOVQ 0(DX), R8
	MOVQ 8(DX), R9
	MOVQ 16(DX), R10
	MOVQ 24(DX), R11
	VPINSRD $0, 0(R8), X13, X4
	VPINSRD $1, 4(R8), X4, X4
	VPINSRQ $1, 8(R8), X4, X4
	VMOVDQU X4, 0(SP)
	VPINSRD $0, 0(R9), X13, X4
	VPINSRD $1, 4(R9), X4, X4
	VPINSRQ $1, 8(R9), X4, X4
	VMOVDQU X4, 16(SP)
	VPINSRD $0, 0(R10), X13, X4
	VPINSRD $1, 4(R10), X4, X4
	VPINSRQ $1, 8(R10), X4, X4
	VMOVDQU X4, 32(SP)
	VPINSRD $0, 0(R11), X13, X4
	VPINSRD $1, 4(R11), X4, X4
	VPINSRQ $1, 8(R11), X4, X4
	VMOVDQU X4, 48(SP)
	VPINSRD $0, 16(R8), X13, X4
	VMOVDQU X4, 128(SP)
	VPINSRD $0, 16(R9), X13, X4
	VMOVDQU X4, 144(SP)
	VPINSRD $0, 16(R10), X13, X4
	VMOVDQU X4, 160(SP)
	VPINSRD $0, 16(R11), X13, X4
	VMOVDQU X4, 176(SP)
	// Lanes 4..7
	MOVQ 32(DX), R8
	MOVQ 40(DX), R9
	MOVQ 48(DX), R10
	MOVQ 56(DX), R11
	VPINSRD $0, 0(R8), X13, X4
	VPINSRD $1, 4(R8), X4, X4
	VPINSRQ $1, 8(R8), X4, X4
	VMOVDQU X4, 64(SP)
	VPINSRD $0, 0(R9), X13, X4
	VPINSRD $1, 4(R9), X4, X4
	VPINSRQ $1, 8(R9), X4, X4
	VMOVDQU X4, 80(SP)
	VPINSRD $0, 0(R10), X13, X4
	VPINSRD $1, 4(R10), X4, X4
	VPINSRQ $1, 8(R10), X4, X4
	VMOVDQU X4, 96(SP)
	VPINSRD $0, 0(R11), X13, X4
	VPINSRD $1, 4(R11), X4, X4
	VPINSRQ $1, 8(R11), X4, X4
	VMOVDQU X4, 112(SP)
	VPINSRD $0, 16(R8), X13, X4
	VMOVDQU X4, 192(SP)
	VPINSRD $0, 16(R9), X13, X4
	VMOVDQU X4, 208(SP)
	VPINSRD $0, 16(R10), X13, X4
	VMOVDQU X4, 224(SP)
	VPINSRD $0, 16(R11), X13, X4
	VMOVDQU X4, 240(SP)

	VMOVDQU ·RC+0(SB), X8
	VMOVDQU ·RC+16(SB), X9
	VMOVDQU 0(AX), X13
	VPXOR X0, X0, X0
	VPXOR X1, X1, X1
	VPXOR X2, X2, X2
	VPXOR X3, X3, X3
	VPXOR X4, X4, X4
	VPXOR X5, X5, X5
	VPXOR X6, X6, X6
	VPXOR X7, X7, X7

loop:
	VMOVDQU 0(BX), X14
	VPXOR X13, X14, X14
	VPXOR X14, X0, X0
	VPXOR X14, X1, X1
	VPXOR X14, X2, X2
	VPXOR X14, X3, X3
	VPXOR X14, X4, X4
	VPXOR X14, X5, X5
	VPXOR X14, X6, X6
	VPXOR X14, X7, X7
	VPXOR 0(SP), X0, X0
	VPXOR 16(SP), X1, X1
	VPXOR 32(SP), X2, X2
	VPXOR 48(SP), X3, X3
	VPXOR 64(SP), X4, X4
	VPXOR 80(SP), X5, X5
	VPXOR 96(SP), X6, X6
	VPXOR 112(SP), X7, X7
	VAESENC X8, X0, X0; VAESENC X8, X1, X1; VAESENC X8, X2, X2; VAESENC X8, X3, X3; VAESENC X8, X4, X4; VAESENC X8, X5, X5; VAESENC X8, X6, X6; VAESENC X8, X7, X7
	VPXOR 128(SP), X0, X0
	VPXOR 144(SP), X1, X1
	VPXOR 160(SP), X2, X2
	VPXOR 176(SP), X3, X3
	VPXOR 192(SP), X4, X4
	VPXOR 208(SP), X5, X5
	VPXOR 224(SP), X6, X6
	VPXOR 240(SP), X7, X7
	VAESENC X9, X0, X0; VAESENC X9, X1, X1; VAESENC X9, X2, X2; VAESENC X9, X3, X3; VAESENC X9, X4, X4; VAESENC X9, X5, X5; VAESENC X9, X6, X6; VAESENC X9, X7, X7
	VAESENC X8, X0, X0; VAESENC X8, X1, X1; VAESENC X8, X2, X2; VAESENC X8, X3, X3; VAESENC X8, X4, X4; VAESENC X8, X5, X5; VAESENC X8, X6, X6; VAESENC X8, X7, X7
	VAESENC X9, X0, X0; VAESENC X9, X1, X1; VAESENC X9, X2, X2; VAESENC X9, X3, X3; VAESENC X9, X4, X4; VAESENC X9, X5, X5; VAESENC X9, X6, X6; VAESENC X9, X7, X7
	ADDQ $16, BX
	DECQ CX
	JNZ loop

	VMOVDQU X0, 0(DI)
	VMOVDQU X1, 16(DI)
	VMOVDQU X2, 32(DI)
	VMOVDQU X3, 48(DI)
	VMOVDQU X4, 64(DI)
	VMOVDQU X5, 80(DI)
	VMOVDQU X6, 96(DI)
	VMOVDQU X7, 112(DI)
	RET
