	VLD1.P 16(R6), [V5.B16]
	VEOR V5.B16, V0.B16, V0.B16
	VEOR V5.B16, V1.B16, V1.B16
	VEOR V5.B16, V2.B16, V2.B16
	VEOR V5.B16, V3.B16, V3.B16
	AESE V8.B16, V0.B16
	AESE V9.B16, V1.B16
	AESE V10.B16, V2.B16
	AESE V11.B16, V3.B16
	AESMC V0.B16, V0.B16
	AESMC V1.B16, V1.B16
	AESMC V2.B16, V2.B16
	AESMC V3.B16, V3.B16
	AESE V28.B16, V0.B16
