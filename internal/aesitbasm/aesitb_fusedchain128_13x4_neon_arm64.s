	VLD1 (R0), [V4.B16]
	MOVD 0(R2), R8
	MOVD 8(R2), R9
	MOVD 16(R2), R10
	MOVD 24(R2), R11
	MOVD $·pad13Tail(SB), R4
	VLD1 (R4), [V5.B16]
	VMOV V5.B16, V8.B16
	MOVD (R8), R12
	VMOV R12, V8.D[0]
	MOVWU 8(R8), R12
	VMOV R12, V8.S[2]
	MOVBU 12(R8), R12
	VMOV R12, V8.B[12]
	VMOV V5.B16, V9.B16
	MOVD (R9), R12
	VMOV R12, V9.D[0]
	MOVWU 8(R9), R12
	VMOV R12, V9.S[2]
	MOVBU 12(R9), R12
	VMOV R12, V9.B[12]
	VMOV V5.B16, V10.B16
	MOVD (R10), R12
	VMOV R12, V10.D[0]
	MOVWU 8(R10), R12
	VMOV R12, V10.S[2]
	MOVBU 12(R10), R12
	VMOV R12, V10.B[12]
	VMOV V5.B16, V11.B16
	MOVD (R11), R12
	VMOV R12, V11.D[0]
	MOVWU 8(R11), R12
	VMOV R12, V11.S[2]
	MOVBU 12(R11), R12
	VMOV R12, V11.B[12]
	VEOR V4.B16, V8.B16, V8.B16
	VEOR V4.B16, V9.B16, V9.B16
	VEOR V4.B16, V10.B16, V10.B16
	VEOR V4.B16, V11.B16, V11.B16
	MOVD $·RC(SB), R4
	VLD1.P 16(R4), [V28.B16]
	VLD1.P 16(R4), [V29.B16]
	VLD1 (R4), [V30.B16]
	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16

