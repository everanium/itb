	AESMC V1.B16, V1.B16
	AESMC V2.B16, V2.B16
	AESMC V3.B16, V3.B16
	VEOR V30.B16, V0.B16, V0.B16
	VEOR V30.B16, V1.B16, V1.B16
	VEOR V30.B16, V2.B16, V2.B16
	VEOR V30.B16, V3.B16, V3.B16
