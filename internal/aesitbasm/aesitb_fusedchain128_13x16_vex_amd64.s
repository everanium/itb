	VMOVDQU X11, 80(SP)

	// Lane 6: idx = base + 6
	MOVQ R8, R9
	ADDQ $6, R9
	VMOVQ R9, X11
	VMOVQ R9, X15
	VPSLLQ $8, X11, X11
