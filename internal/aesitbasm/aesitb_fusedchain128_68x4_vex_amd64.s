//go:build amd64 && !purego && !noitbasm

// VEX-encoded AES-NI XMM fused ChainHash cascade kernel for AES-ITB-128 at the
// 68-byte shape, 4 lanes (5 PKCS#7 blocks, 7 AES rounds per
// cascade round).
// The padded data blocks are staged once into the frame and every
// cascade round runs from those 16-byte slots; see aesitbasm_fused.go for the
// construction and the in-package parity tests for the bit-exact pin
// against the pure-Go cascade.

#include "textflag.h"

// func aesITB128FusedChain68x4VexAsm(key *[16]byte, comps *uint64, nPairs int, dataPtrs *[4]*byte, out *[4][2]uint64)
TEXT ·aesITB128FusedChain68x4VexAsm(SB), NOSPLIT, $320-40
	MOVQ key+0(FP), AX
	MOVQ comps+8(FP), BX
	MOVQ nPairs+16(FP), CX
	MOVQ dataPtrs+24(FP), DX
	MOVQ out+32(FP), DI
	MOVQ 0(DX), R8
	MOVQ 8(DX), R9
	MOVQ 16(DX), R10
	MOVQ 24(DX), R11

	VMOVDQU ·pad4Tail(SB), X13
	VPINSRD $0, 0(R8), X13, X4
	VPINSRD $1, 4(R8), X4, X4
	VPINSRQ $1, 8(R8), X4, X4
	VMOVDQU X4, 0(SP)
	VPINSRD $0, 0(R9), X13, X4
	VPINSRD $1, 4(R9), X4, X4
	VPINSRQ $1, 8(R9), X4, X4
	VMOVDQU X4, 16(SP)
	VPINSRD $0, 0(R10), X13, X4
	VPINSRD $1, 4(R10), X4, X4
	VPINSRQ $1, 8(R10), X4, X4
	VMOVDQU X4, 32(SP)
	VPINSRD $0, 0(R11), X13, X4
	VPINSRD $1, 4(R11), X4, X4
	VPINSRQ $1, 8(R11), X4, X4
	VMOVDQU X4, 48(SP)
	VMOVDQU 16(R8), X4
	VMOVDQU X4, 64(SP)
	VMOVDQU 16(R9), X4
	VMOVDQU X4, 80(SP)
	VMOVDQU 16(R10), X4
	VMOVDQU X4, 96(SP)
	VMOVDQU 16(R11), X4
	VMOVDQU X4, 112(SP)
	VMOVDQU 32(R8), X4
	VMOVDQU X4, 128(SP)
	VMOVDQU 32(R9), X4
	VMOVDQU X4, 144(SP)
	VMOVDQU 32(R10), X4
	VMOVDQU X4, 160(SP)
	VMOVDQU 32(R11), X4
	VMOVDQU X4, 176(SP)
	VMOVDQU 48(R8), X4
	VMOVDQU X4, 192(SP)
	VMOVDQU 48(R9), X4
	VMOVDQU X4, 208(SP)
	VMOVDQU 48(R10), X4
	VMOVDQU X4, 224(SP)
	VMOVDQU 48(R11), X4
	VMOVDQU X4, 240(SP)
	VPINSRD $0, 64(R8), X13, X4
	VMOVDQU X4, 256(SP)
	VPINSRD $0, 64(R9), X13, X4
	VMOVDQU X4, 272(SP)
	VPINSRD $0, 64(R10), X13, X4
	VMOVDQU X4, 288(SP)
	VPINSRD $0, 64(R11), X13, X4
	VMOVDQU X4, 304(SP)

	VMOVDQU ·RC+0(SB), X5
	VMOVDQU ·RC+16(SB), X6
	VMOVDQU ·RC+32(SB), X7
	VMOVDQU ·RC+48(SB), X8
	VMOVDQU ·RC+64(SB), X9
	VMOVDQU ·RC+80(SB), X10
	VMOVDQU ·RC+96(SB), X11
	VMOVDQU ·RC+112(SB), X12
	VMOVDQU 0(AX), X13
	VPXOR X0, X0, X0
	VPXOR X1, X1, X1
	VPXOR X2, X2, X2
	VPXOR X3, X3, X3

loop:
	VMOVDQU 0(BX), X14
	VPXOR X13, X14, X14
	VPXOR X14, X0, X0
	VPXOR X14, X1, X1
	VPXOR X14, X2, X2
	VPXOR X14, X3, X3
	VPXOR 0(SP), X0, X0
	VPXOR 16(SP), X1, X1
	VPXOR 32(SP), X2, X2
	VPXOR 48(SP), X3, X3
	VAESENC X5, X0, X0; VAESENC X5, X1, X1; VAESENC X5, X2, X2; VAESENC X5, X3, X3
	VPXOR 64(SP), X0, X0
	VPXOR 80(SP), X1, X1
	VPXOR 96(SP), X2, X2
	VPXOR 112(SP), X3, X3
	VAESENC X6, X0, X0; VAESENC X6, X1, X1; VAESENC X6, X2, X2; VAESENC X6, X3, X3
	VPXOR 128(SP), X0, X0
	VPXOR 144(SP), X1, X1
	VPXOR 160(SP), X2, X2
	VPXOR 176(SP), X3, X3
	VAESENC X7, X0, X0; VAESENC X7, X1, X1; VAESENC X7, X2, X2; VAESENC X7, X3, X3
	VPXOR 192(SP), X0, X0
	VPXOR 208(SP), X1, X1
	VPXOR 224(SP), X2, X2
	VPXOR 240(SP), X3, X3
	VAESENC X8, X0, X0; VAESENC X8, X1, X1; VAESENC X8, X2, X2; VAESENC X8, X3, X3
	VPXOR 256(SP), X0, X0
	VPXOR 272(SP), X1, X1
	VPXOR 288(SP), X2, X2
	VPXOR 304(SP), X3, X3
	VAESENC X9, X0, X0; VAESENC X9, X1, X1; VAESENC X9, X2, X2; VAESENC X9, X3, X3
	VAESENC X5, X0, X0; VAESENC X5, X1, X1; VAESENC X5, X2, X2; VAESENC X5, X3, X3
	VAESENC X6, X0, X0; VAESENC X6, X1, X1; VAESENC X6, X2, X2; VAESENC X6, X3, X3
	ADDQ $16, BX
	DECQ CX
	JNZ loop

	VMOVDQU X0, 0(DI)
	VMOVDQU X1, 16(DI)
	VMOVDQU X2, 32(DI)
	VMOVDQU X3, 48(DI)
	RET
