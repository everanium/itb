// areion512Permutex4RC(x0, x1, x2, x3 *aes.Block4, rc *[15][16]byte) —
// 15 rounds under the constant table rc + final rotation.
//
// Per-round structure (areion512Roundx4):
//   temp1 = a; RoundNoKey(temp1); b ^= temp1
//   temp2 = c; RoundNoKey(temp2); d ^= temp2
//   FinalRoundNoKey(a)
//   FinalRoundNoKey(c); c ^= rc; RoundNoKey(c)
//
// Outer rotation across 15 rounds — round r argument tuple is
// (x_(0+r mod 4), x_(1+r mod 4), x_(2+r mod 4), x_(3+r mod 4)).
// ASM mirrors that by rotating the *register role* each round.
//
// Layout:
//   v0..v3   — x0 across lanes 0..3
//   v4..v7   — x1
//   v8..v11  — x2
