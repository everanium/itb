// func blake3XORBlocksAvx512Asm(keyWords *[8]uint32, nonce *[4]uint32, counter uint64, dst, src *byte, nBlocks int)
TEXT ·blake3XORBlocksAvx512Asm(SB), NOSPLIT, $0-48
	MOVQ keyWords+0(FP), AX
	MOVQ nonce+8(FP), BX
	MOVQ counter+16(FP), CX
	MOVQ dst+24(FP), DX
	MOVQ src+32(FP), SI
	MOVQ nBlocks+40(FP), DI

	VPBROADCASTD 0(AX), Y16
	VPBROADCASTD 4(AX), Y17
	VPBROADCASTD 8(AX), Y18
	VPBROADCASTD 12(AX), Y19
	VPBROADCASTD 16(AX), Y20
	VPBROADCASTD 20(AX), Y21
	VPBROADCASTD 24(AX), Y22
	VPBROADCASTD 28(AX), Y23

	VPBROADCASTD 0(BX), Y24
	VPBROADCASTD 4(BX), Y25
	VPBROADCASTD 8(BX), Y26
	VPBROADCASTD 12(BX), Y27

	VPBROADCASTQ CX, Y28
	VPADDQ b3CtrInit0<>(SB), Y28, Y28
	VPBROADCASTQ CX, Y29
	VPADDQ b3CtrInit1<>(SB), Y29, Y29

loop8:
	CMPQ DI, $8
	JLT tail_check

	VPSHUFD $0xd8, Y28, Y0
	VPSHUFD $0xd8, Y29, Y1
	VPUNPCKLQDQ Y1, Y0, Y30
	VPUNPCKHQDQ Y1, Y0, Y31

	VMOVDQA32 Y16, Y0
	VMOVDQA32 Y17, Y1
	VMOVDQA32 Y18, Y2
	VMOVDQA32 Y19, Y3
	VMOVDQA32 Y20, Y4
	VMOVDQA32 Y21, Y5
	VMOVDQA32 Y22, Y6
	VMOVDQA32 Y23, Y7

	VPBROADCASTD b3CTRTab<>+0(SB), Y8
	VPBROADCASTD b3CTRTab<>+4(SB), Y9
	VPBROADCASTD b3CTRTab<>+8(SB), Y10
	VPBROADCASTD b3CTRTab<>+12(SB), Y11
	VPXOR Y12, Y12, Y12
	VPXOR Y13, Y13, Y13
	VPBROADCASTD b3CTRTab<>+24(SB), Y14
	VPBROADCASTD b3CTRTab<>+28(SB), Y15

	B3_ROUNDS_24_EVEX(Y0,Y1,Y2,Y3,Y4,Y5,Y6,Y7,Y8,Y9,Y10,Y11,Y12,Y13,Y14,Y15,Y24,Y25,Y26,Y27,Y30,Y31)

	VPXORD Y8, Y0, Y0
	VPXORD Y9, Y1, Y1
	VPXORD Y10, Y2, Y2
	VPXORD Y11, Y3, Y3
	VPXORD Y12, Y4, Y4
	VPXORD Y13, Y5, Y5
	VPXORD Y14, Y6, Y6
	VPXORD Y15, Y7, Y7

	TRANSPOSE_8x8_YMM

	VPXOR 0(SI), Y0, Y0
	VPXOR 32(SI), Y1, Y1
	VPXOR 64(SI), Y2, Y2
	VPXOR 96(SI), Y3, Y3
	VPXOR 128(SI), Y4, Y4
	VPXOR 160(SI), Y5, Y5
	VPXOR 192(SI), Y6, Y6
	VPXOR 224(SI), Y7, Y7

	VMOVDQU Y0, 0(DX)
	VMOVDQU Y1, 32(DX)
	VMOVDQU Y2, 64(DX)
	VMOVDQU Y3, 96(DX)
	VMOVDQU Y4, 128(DX)
	VMOVDQU Y5, 160(DX)
	VMOVDQU Y6, 192(DX)
	VMOVDQU Y7, 224(DX)

	VPADDQ b3CtrStep8<>(SB), Y28, Y28
	VPADDQ b3CtrStep8<>(SB), Y29, Y29
	ADDQ $256, SI
	ADDQ $256, DX
	SUBQ $8, DI
	JMP loop8

tail_check:
	TESTQ DI, DI
	JZ done

	VPSHUFD $0xd8, Y28, Y0
	VPSHUFD $0xd8, Y29, Y1
	VPUNPCKLQDQ Y1, Y0, Y30
	VPUNPCKHQDQ Y1, Y0, Y31

	VMOVDQA32 Y16, Y0
	VMOVDQA32 Y17, Y1
	VMOVDQA32 Y18, Y2
	VMOVDQA32 Y19, Y3
	VMOVDQA32 Y20, Y4
	VMOVDQA32 Y21, Y5
	VMOVDQA32 Y22, Y6
	VMOVDQA32 Y23, Y7

	VPBROADCASTD b3CTRTab<>+0(SB), Y8
	VPBROADCASTD b3CTRTab<>+4(SB), Y9
	VPBROADCASTD b3CTRTab<>+8(SB), Y10
	VPBROADCASTD b3CTRTab<>+12(SB), Y11
	VPXOR Y12, Y12, Y12
	VPXOR Y13, Y13, Y13
	VPBROADCASTD b3CTRTab<>+24(SB), Y14
	VPBROADCASTD b3CTRTab<>+28(SB), Y15

	B3_ROUNDS_24_EVEX(Y0,Y1,Y2,Y3,Y4,Y5,Y6,Y7,Y8,Y9,Y10,Y11,Y12,Y13,Y14,Y15,Y24,Y25,Y26,Y27,Y30,Y31)

	VPXORD Y8, Y0, Y0
	VPXORD Y9, Y1, Y1
	VPXORD Y10, Y2, Y2
	VPXORD Y11, Y3, Y3
	VPXORD Y12, Y4, Y4
	VPXORD Y13, Y5, Y5
	VPXORD Y14, Y6, Y6
	VPXORD Y15, Y7, Y7

	TRANSPOSE_8x8_YMM

	// Store at most DI blocks (1..7).
	VPXOR 0(SI), Y0, Y0
	VMOVDQU Y0, 0(DX)
	CMPQ DI, $1
	JE done

	VPXOR 32(SI), Y1, Y1
	VMOVDQU Y1, 32(DX)
	CMPQ DI, $2
	JE done

	VPXOR 64(SI), Y2, Y2
	VMOVDQU Y2, 64(DX)
	CMPQ DI, $3
	JE done

	VPXOR 96(SI), Y3, Y3
	VMOVDQU Y3, 96(DX)
	CMPQ DI, $4
	JE done

	VPXOR 128(SI), Y4, Y4
	VMOVDQU Y4, 128(DX)
	CMPQ DI, $5
	JE done

	VPXOR 160(SI), Y5, Y5
	VMOVDQU Y5, 160(DX)
	CMPQ DI, $6
	JE done

	VPXOR 192(SI), Y6, Y6
	VMOVDQU Y6, 192(DX)

done:
	WIPE_ZMM_ALL
	XORQ AX, AX
	XORQ BX, BX
	XORQ CX, CX
	XORQ DX, DX
	XORQ SI, SI
	XORQ DI, DI
	RET

// func blake3Batch24x4Avx512Asm(keyWords *[8]uint32, ptrs *[8]*byte)
TEXT ·blake3Batch24x4Avx512Asm(SB), NOSPLIT, $0-16
	MOVQ keyWords+0(FP), AX
	MOVQ ptrs+8(FP), BX

	MOVQ 0(BX), R8
	MOVQ 8(BX), R9
	MOVQ 16(BX), R10
	MOVQ 24(BX), R11

	// Load and transpose 4 x 24B messages into X24..X29.
	VMOVDQU 0(R8), X0
	VMOVDQU 0(R9), X1
	VMOVDQU 0(R10), X2
	VMOVDQU 0(R11), X3
	VPUNPCKLDQ X1, X0, X4
	VPUNPCKHDQ X1, X0, X5
	VPUNPCKLDQ X3, X2, X6
	VPUNPCKHDQ X3, X2, X7
	VPUNPCKLQDQ X6, X4, X24
	VPUNPCKHQDQ X6, X4, X25
	VPUNPCKLQDQ X7, X5, X26
	VPUNPCKHQDQ X7, X5, X27

	VMOVQ 16(R8), X0
	VMOVQ 16(R9), X1
	VMOVQ 16(R10), X2
	VMOVQ 16(R11), X3
	VPUNPCKLDQ X1, X0, X4
	VPUNPCKLDQ X3, X2, X6
	VPUNPCKLQDQ X6, X4, X28
	VPUNPCKHQDQ X6, X4, X29

	VPBROADCASTD 0(AX), X0
	VPBROADCASTD 4(AX), X1
	VPBROADCASTD 8(AX), X2
	VPBROADCASTD 12(AX), X3
	VPBROADCASTD 16(AX), X4
	VPBROADCASTD 20(AX), X5
	VPBROADCASTD 24(AX), X6
	VPBROADCASTD 28(AX), X7

	VPBROADCASTD b3CTRTab<>+0(SB), X8
	VPBROADCASTD b3CTRTab<>+4(SB), X9
	VPBROADCASTD b3CTRTab<>+8(SB), X10
	VPBROADCASTD b3CTRTab<>+12(SB), X11
	VPXOR X12, X12, X12
	VPXOR X13, X13, X13
	VPBROADCASTD b3CTRTab<>+24(SB), X14
	VPBROADCASTD b3CTRTab<>+28(SB), X15

	B3_ROUNDS_24_EVEX(X0,X1,X2,X3,X4,X5,X6,X7,X8,X9,X10,X11,X12,X13,X14,X15,X24,X25,X26,X27,X28,X29)

	VPXORD X8, X0, X0
	VPXORD X9, X1, X1
	VPXORD X10, X2, X2
	VPXORD X11, X3, X3
	VPXORD X12, X4, X4
