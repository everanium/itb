	VPUNPCKHDQ X5, X4, X13; \
	VPUNPCKLDQ X7, X6, X14; \
	VPUNPCKHDQ X7, X6, X15; \
	VPUNPCKLQDQ X10, X8, X0; \
	VPUNPCKHQDQ X10, X8, X2; \
	VPUNPCKLQDQ X11, X9, X4; \
	VPUNPCKHQDQ X11, X9, X6; \
	VPUNPCKLQDQ X14, X12, X1; \
