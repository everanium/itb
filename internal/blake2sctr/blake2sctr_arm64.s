// ARM64 NEON 4-lane (V.4S SOV) RFC 7693 Keyed BLAKE2s-256 CTR keystream XOR
// and 4-lane batch-PRF kernels with $0 stack frame and full vector/GPR
// register zeroization before return.
//
// Register allocation (blake2sXORBlocksNeonAsm & blake2sBatch24x4NeonAsm):
//   V0..V15   working state words v[0..15] across 4 parallel lanes
//   V16..V23  preloaded hKey[0..7] broadcast across 4 lanes
//   V24..V27  m[0..3] (nonce[0..3] or transposed input words 0..3)
//   V28, V29  m[4..5] (per-lane 64-bit counter lo/hi or input words 4..5)
//   V30       ror8 byte-shuffle table for 8-bit right rotation via VTBL
//   V31       rotate scratch for 12-bit and 7-bit right rotations
//
// Stack frame: $0 on all entry points.

#include "textflag.h"

#define B2S_NEON_G(a, b, c, d, mx, my) \
	VADD b.S4, a.S4, a.S4; \
	VADD mx.S4, a.S4, a.S4; \
	VEOR a.B16, d.B16, d.B16; \
	VREV32 d.H8, d.H8; \
	VADD d.S4, c.S4, c.S4; \
	VEOR c.B16, b.B16, b.B16; \
	VSHL $20, b.S4, V31.S4; \
	VSRI $12, b.S4, V31.S4; \
	VADD V31.S4, a.S4, a.S4; \
	VADD my.S4, a.S4, a.S4; \
	VEOR a.B16, d.B16, d.B16; \
	VTBL V30.B16, [d.B16], d.B16; \
	VADD d.S4, c.S4, c.S4; \
	VEOR c.B16, V31.B16, V31.B16; \
	VSHL $25, V31.S4, b.S4; \
	VSRI $7, V31.S4, b.S4

