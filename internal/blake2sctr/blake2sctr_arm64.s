	VEOR V10.B16, V2.B16, V2.B16
	VEOR V18.B16, V2.B16, V2.B16
	VEOR V11.B16, V3.B16, V3.B16
	VEOR V19.B16, V3.B16, V3.B16
	VEOR V12.B16, V4.B16, V4.B16
