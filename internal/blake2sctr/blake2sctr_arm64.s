	VMOV R11, V29.D[0]
	LSR $32, R9, R11
	LSR $32, R10, R10
	ORR R10<<32, R11, R11
	VMOV R11, V29.D[1]
	ADD $4, R2, R2

	VMOV V16.B16, V0.B16
	VMOV V17.B16, V1.B16
	VMOV V18.B16, V2.B16
	VMOV V19.B16, V3.B16
	VMOV V20.B16, V4.B16
	VMOV V21.B16, V5.B16
	VMOV V22.B16, V6.B16
	VMOV V23.B16, V7.B16

