// AVX-512VL (EVEX YMM 8-lane SOV / XMM 4-lane SOV) and AVX2 (VEX XMM 4-lane
// SOV) RFC 7693 Keyed BLAKE2s-256 CTR keystream XOR and 4-lane batch-PRF
// kernels.
//
// Construction (per 32-byte CTR block b = 0..nBlocks-1 at counter c = counter + b):
//   v[0..7]   = hKey[0..7] (precomputed non-final block-0 key state)
//   v[8..11]  = IV[0..3]
//   v[12]     = IV[4] ^ 88 (t0 = 64 + 24)
//   v[13]     = IV[5]      (t1 = 0)
//   v[14]     = IV[6] ^ 0xffffffff (f0 = final block)
//   v[15]     = IV[7]      (f1 = 0)
//   m[0..3]   = nonce[0..3]
//   m[4]      = uint32(c)
//   m[5]      = uint32(c >> 32)
//   m[6..15]  = 0 (elided at compile time in G macros)
//   out[0..7] = hKey[0..7] ^ v'[0..7] ^ v'[8..15] after 10 rounds
//   dst[32*b..32*b+31] = src[32*b..32*b+31] ^ out[0..7]
// Matches RFC 7693 / golang.org/x/crypto/blake2s.New256 bit-for-bit.
//
// Register allocation (blake2sXORBlocksAvx512Asm):
//   Y0..Y15 / X0..X15  working state words v[0..15] across 8 or 4 blocks
//   Y16..Y23           broadcast hKey[0..7]
//   Y24..Y27           broadcast nonce[0..3] (m[0..3])
//   Y28, Y29           per-lane 64-bit counters [c+0,c+1,c+4,c+5], [c+2,c+3,c+6,c+7]
//   Y30, Y31           per-lane m[4] (counter lo) and m[5] (counter hi)
//
// Register allocation (blake2sXORBlocksAvx2Asm):
//   X0..X14            working state words v[0..14] across 4 blocks
//   X15 / X12          working state word v[15]/v[12] + rotate/broadcast scratch
//   R12, R13           64-bit GPR spill pair for X15 / X12 during round
//   R8, R9             64-bit GPR pair holding m[4] (counter lo across 4 lanes)
//   R10, R11           64-bit GPR pair holding m[5] (counter hi across 4 lanes)
//
// Stack frame: $0 on all entry points (100% register-resident).

