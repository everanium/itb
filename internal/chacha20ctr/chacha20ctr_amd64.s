// AVX-512 (EVEX YMM 8-lane SOV / XMM 4-lane SOV / XMM 1-lane) and AVX2
// (VEX YMM 4-block / XMM 1-block) RFC 8439 ChaCha20 keystream XOR kernels.
//
// Construction (per 64-byte block b = 0..nBlocks-1 at counter c = counter + b):
//   state[0..3]   = [0x61707865, 0x3320646e, 0x79622d32, 0x6b206574]
//   state[4..11]  = key[0..7]
//   state[12]     = uint32(counter + b)
//   state[13..15] = nonce[0..2]
//   working       = 20-round ChaCha20 permutation(state)
//   keystream     = working + state (mod 2^32 per word, little-endian)
//   dst[64*b..64*b+63] = src[64*b..64*b+63] ^ keystream
// Matches RFC 8439 § 2.3 / golang.org/x/crypto/chacha20 bit-for-bit.
//
// Register allocation (chacha20XORBlocksAvx512Asm):
//   Y0..Y15   working state words v[0..15] across 8 parallel blocks (loop8)
//   X0..X15   working state words v[0..15] across 4 parallel blocks (block4)
//   X0..X3    working state rows 0..3 of 1 block (loop1)
//   Y16..Y23  broadcast key[0..7]
//   Y24..Y26  broadcast nonce[0..2]
//   Y27       per-lane block counter vector [c+0..c+7] (or [c, n0, n1, n2] in loop1)
//   Y28..Y31  4x4 transpose scratch (and row constants in loop1)
//
// Register allocation (chacha20XORBlocksAvx2Asm):
//   Y0..Y3    rows 0..3 of blocks (b, b+1) in low/high 128-bit lanes
//   Y4..Y7    rows 0..3 of blocks (b+2, b+3) in low/high 128-bit lanes
//   Y8, Y9    rotate / transpose scratch
//   Y10, Y11  PSHUFB byte-rotate masks (rol16, rol8)
//   Y12       sigma row broadcast
//   Y13, Y14  key[0..3] and key[4..7] row broadcasts
//   Y15       counter+nonce row for blocks (b, b+1)
//
// Stack frame: $0 (zero bytes; 100% register-resident).

