// ARM64 NEON (2x2-lane interleaved V.2D) SipHash-2-4-128 counter-mode
// keystream XOR and 4-lane batch PRF kernels.
//
// CTR construction (per 16-byte block b = 0..nBlocks-1 starting from vInit):
//   m1            = nonceLo ^ (counter + uint64(b))
//   v0..v3        = vInit[0..2], vInit[3] ^ m1
//   v0..v3        = 2 * SipRound(v0..v3); v0 ^= m1
//   bPad          = uint64(16) << 56
//   v3           ^= bPad; v0..v3 = 2 * SipRound(v0..v3); v0 ^= bPad
//   v2           ^= 0xee; v0..v3 = 4 * SipRound(v0..v3); lo = (v0 ^ v1) ^ (v2 ^ v3)
//   v1           ^= 0xdd; v0..v3 = 4 * SipRound(v0..v3); hi = (v0 ^ v1) ^ (v2 ^ v3)
//   dst[16*b..16*b+15] = src[16*b..16*b+15] ^ (LE64(lo) || LE64(hi))
// Matches Block128Raw(k0, k1, nonceHi, nonceLo ^ (counter + b)) bit-for-bit.
//
// Register allocation (siphashXORBlocksNEONAsm):
//   V0, V2, V4, V6   working state v0..v3 for lanes (0, 1)
//   V1, V3, V5, V7   working state v0..v3 for lanes (2, 3)
//   V8, V9           lo output words for lanes (0, 1) and (2, 3)
//   V10, V11         hi output words for lanes (0, 1) and (2, 3)
//   V12, V13         m1 message words and zipped block 0..1 keystream
//   V14, V15         zipped block 2..3 keystream
//   V16..V19         SipRound rotate scratch and src block loads
//   V20..V23         duplicated vInit[0..3]
//   V24              duplicated 0xee
//   V25              duplicated 0xdd
//   V26              duplicated bPad (0x1000000000000000)
//   V27              duplicated nonceLo
//   V28, V29         per-lane 64-bit block counter vectors [c+0, c+1] and [c+2, c+3]
//   V30              constant [4, 4]
//   V31              constant [1, 1]
//
// Stack frame: $0 (zero bytes; 100% register-resident across all kernels).

