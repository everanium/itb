	VPROLQ $16, a3, a3; VPROLQ $16, b3, b3; \
	VPXORQ a2, a3, a3; VPXORQ b2, b3, b3; \
	VPADDQ a3, a0, a0; VPADDQ b3, b0, b0; \
	VPROLQ $21, a3, a3; VPROLQ $21, b3, b3; \
