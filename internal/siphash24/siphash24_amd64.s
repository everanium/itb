// AVX-512VL (EVEX YMM 8-lane / 4-lane / XMM 1-lane) and AVX2 (VEX YMM 4-lane /
// XMM 1-lane) SipHash-2-4-128 counter-mode keystream XOR and 4-lane batch PRF
// kernels.
//
// CTR construction (per 16-byte block b = 0..nBlocks-1 starting from vInit):
//   m1            = nonceLo ^ (counter + uint64(b))
//   v0..v3        = vInit[0..2], vInit[3] ^ m1
//   v0..v3        = 2 * SipRound(v0..v3); v0 ^= m1
//   bPad          = uint64(16) << 56
//   v3           ^= bPad; v0..v3 = 2 * SipRound(v0..v3); v0 ^= bPad
//   v2           ^= 0xee; v0..v3 = 4 * SipRound(v0..v3); lo = (v0 ^ v1) ^ (v2 ^ v3)
//   v1           ^= 0xdd; v0..v3 = 4 * SipRound(v0..v3); hi = (v0 ^ v1) ^ (v2 ^ v3)
//   dst[16*b..16*b+15] = src[16*b..16*b+15] ^ (LE64(lo) || LE64(hi))
// Matches Block128Raw(k0, k1, nonceHi, nonceLo ^ (counter + b)) bit-for-bit.
//
// Register allocation (siphashXORBlocksAvx512Asm):
//   Y0..Y3    working state v0..v3 for blocks 0..3 (or X0..X3 in 1-block tail)
//   Y4..Y7    working state v0..v3 for blocks 4..7 in 8-block loop
//   Y8..Y15   m1 / lo / hi / interleave scratch
//   Y16..Y19  broadcast vInit[0..3]
//   Y20       broadcast nonceLo
//   Y21       broadcast bPad (0x1000000000000000)
//   Y22       broadcast 0xee
//   Y23       broadcast 0xdd
//   Y24, Y25  per-lane 64-bit block counter vectors [c+0..c+3] and [c+4..c+7]
//
// Register allocation (siphashXORBlocksAvx2Asm):
//   Y0..Y3    working state v0..v3 for blocks 0..3 (or X0..X3 in 1-block tail)
//   Y4, Y5    m1 / lo / rotate and interleave scratch
//   Y6        rol16 byte-shuffle mask
//   Y7        broadcast 0xdd
//   Y8..Y11   broadcast vInit[0..3]
//   Y12       broadcast nonceLo
//   Y13       broadcast bPad (0x1000000000000000)
//   Y14       broadcast 0xee
//   Y15       per-lane 64-bit block counter vector [c+0..c+3]
//
// Stack frame: $0 (zero bytes; 100% register-resident across all kernels).

